# =========================================================
# DIGITAL TWIN
# =========================================================

class DigitalTwin:

    def __init__(self):

        self.devices = DEVICES.copy()

        self.current_target = "ESP32-01"

        self.current_scenario = "NORMAL"

        self.history: List[Dict] = []

        self.sequence_counter = 0

        self.event_counter = 0

        print("=" * 60)
        print("IOT DIGITAL TWIN INITIALIZED")
        print("=" * 60)

        print(
            f"Devices: {len(self.devices)}"
        )

        print(
            f"Validated sequences: "
            f"{VALIDATED_DIR}"
        )

        print(
            f"Scenarios available: "
            f"{len(SCENARIOS)}"
        )


        # -----------------------------------------------------
        # Check validated files
        # -----------------------------------------------------

        print("\nChecking validated sequences...")

        for scenario_name, scenario in SCENARIOS.items():

            sequence_path = (
                VALIDATED_DIR
                / scenario["file"]
            )

            if sequence_path.exists():

                print(
                    f"  [OK] {scenario_name}"
                )

            else:

                print(
                    f"  [MISSING] {scenario_name}"
                    f" - FILE NOT FOUND"
                )

        print()


    # =====================================================
    # DEVICES
    # =====================================================

    def get_devices(self) -> Dict:

        return self.devices


    def set_target(
        self,
        device_id: str,
    ):

        if device_id not in self.devices:

            raise ValueError(
                f"Unknown device: {device_id}"
            )

        self.current_target = device_id


    # =====================================================
    # SCENARIO
    # =====================================================

    def set_scenario(
        self,
        scenario: str,
    ):

        scenario = scenario.upper()

        if scenario not in SCENARIOS:

            raise ValueError(
                f"Unknown scenario: {scenario}"
            )

        self.current_scenario = scenario

        # Reset sequence counter when scenario changes
        self.sequence_counter = 0

        print(
            "\nDigital Twin scenario changed:"
        )

        print(
            f"  Target  : "
            f"{self.current_target}"
        )

        print(
            f"  Scenario: "
            f"{scenario}"
        )

        print(
            f"  Label   : "
            f"{SCENARIOS[scenario]['label']}"
        )


    # =====================================================
    # LOAD VALIDATED SEQUENCE
    # =====================================================

    def get_next_sequence(
        self,
    ) -> np.ndarray:

        scenario = SCENARIOS[
            self.current_scenario
        ]

        sequence_path = (
            VALIDATED_DIR
            / scenario["file"]
        )

        if not sequence_path.exists():

            raise FileNotFoundError(
                f"Validated sequence not found: "
                f"{sequence_path}"
            )

        sequence = np.load(
            sequence_path
        ).astype(
            np.float32
        )

        # -------------------------------------------------
        # Validate exact CNN-LSTM input dimensions
        # -------------------------------------------------

        if sequence.shape != (
            10,
            115,
        ):

            raise ValueError(
                f"Invalid sequence shape: "
                f"{sequence.shape}. "
                f"Expected (10, 115)."
            )

        self.sequence_counter += 1

        print(
            f"Sequence loaded:"
            f" {scenario['file']}"
        )

        print(
            f"Sequence shape:"
            f" {sequence.shape}"
        )

        print(
            f"Sequence number:"
            f" {self.sequence_counter}"
        )

        return sequence


    # =====================================================
    # SCENARIO INFO
    # =====================================================

    def get_scenario_info(
        self,
    ) -> Dict:

        scenario = SCENARIOS[
            self.current_scenario
        ]

        return {

            "scenario":
                self.current_scenario,

            "label":
                scenario["label"],

            "expected":
                scenario["expected"],

            "target_device":
                self.current_target,

            "attack_type":
                scenario["attack_type"],

            "validated_sequence":
                scenario["file"],
        }


    # =====================================================
    # AVAILABLE SCENARIOS
    # =====================================================

    def get_scenarios(
        self,
    ) -> Dict:

        return SCENARIOS.copy()


    # =====================================================
    # RECORD EVENT
    # =====================================================

    def record_event(
        self,
        prediction: Dict,
    ) -> Dict:

        scenario = SCENARIOS[
            self.current_scenario
        ]

        self.event_counter += 1

        # -------------------------------------------------
        # Real event timestamp
        # -------------------------------------------------

        now = datetime.now(
            timezone.utc
        )

        timestamp = now.isoformat()

        created_at = int(
            now.timestamp() * 1000
        )

        # -------------------------------------------------
        # Determine attack type
        # -------------------------------------------------

        attack_type = scenario[
            "attack_type"
        ]

        # If ML says BENIGN, there is
        # no detected attack type.
        if prediction["prediction"] == "BENIGN":

            attack_type = None

        # -------------------------------------------------
        # Build event
        # -------------------------------------------------

        event = {

            # =============================================
            # EVENT
            # =============================================

            "id":
                self.event_counter,

            "created_at":
                created_at,

            "timestamp":
                timestamp,

            # =============================================
            # DEVICE
            # =============================================

            "device":
                self.current_target,

            "source_ip":
                self.current_target,

            "destination_ip":
                "DIGITAL-TWIN",

            "protocol":
                "Wi-Fi",

            "device_status":
                self.devices[
                    self.current_target
                ]["status"],

            # =============================================
            # DIGITAL TWIN
            # =============================================

            "digital_twin":
                "ACTIVE",

            "scenario":
                self.current_scenario,

            "scenario_label":
                scenario["label"],

            "attack_type":
                attack_type,

            "expected":
                scenario["expected"],

            # =============================================
            # ML RESULT
            # =============================================

            "prediction":
                prediction["prediction"],

            "confidence_score":
                prediction[
                    "confidence_score"
                ],

            "attack_probability":
                prediction[
                    "attack_probability"
                ],

            "risk_level":
                prediction[
                    "risk_level"
                ],

            "model_name":
                prediction[
                    "model_name"
                ],

        }

        # -------------------------------------------------
        # Newest event first
        # -------------------------------------------------

        self.history.insert(
            0,
            event,
        )

        # -------------------------------------------------
        # Keep history bounded
        # -------------------------------------------------

        self.history = (
            self.history[:100]
        )

        return event


    # =====================================================
    # HISTORY
    # =====================================================

    def get_history(
        self,
    ) -> List[Dict]:

        return self.history.copy()


